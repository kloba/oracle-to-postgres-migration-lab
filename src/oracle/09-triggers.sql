-- =====================================================================================
-- 11-13 : AFTER INSERT OR UPDATE OR DELETE ... FOR EACH ROW -- the audit trail
-- =====================================================================================
-- MIGRATION NOTE (H-02, the expensive one): these three call pkg_audit, which is
-- PRAGMA AUTONOMOUS_TRANSACTION. Converting that to a dblink self-connection means a new
-- backend connection *per row*, which is unusable on a per-row audit trigger. The
-- realistic conversion drops the autonomy and writes in the same transaction, which
-- means audit rows now roll back alongside the change they describe. That is a real
-- behaviour change with compliance implications and it needs signing off, not
-- converting. See docs/04-review-tasks.md.
-- -------------------------------------------------------------------------------------

CREATE OR REPLACE TRIGGER trg_aiud_customer
  AFTER INSERT OR UPDATE OR DELETE ON customer
  FOR EACH ROW
DECLARE
  l_action CHAR(1);
  l_pk     VARCHAR2(200);
  l_old    VARCHAR2(4000);
  l_new    VARCHAR2(4000);
BEGIN
  -- MIGRATION NOTE (H-25): INSERTING / UPDATING / DELETING become TG_OP = 'INSERT' etc.
  -- in PL/pgSQL. The conversion is mechanical; the trap is that PostgreSQL's OLD is NULL
  -- (not a record of NULLs) during INSERT, so :OLD.customer_id -> OLD.customer_id raises
  -- rather than returning NULL. Guard on TG_OP first, always.
  IF INSERTING THEN
    l_action := 'I';
    l_pk     := TO_CHAR(:NEW.customer_id);
    l_new    := :NEW.customer_ref || '|' || :NEW.last_name || '|' || :NEW.status;
  ELSIF UPDATING THEN
    l_action := 'U';
    l_pk     := TO_CHAR(:OLD.customer_id);
    l_old    := :OLD.customer_ref || '|' || :OLD.last_name || '|' || :OLD.status;
    l_new    := :NEW.customer_ref || '|' || :NEW.last_name || '|' || :NEW.status;
  ELSE
    l_action := 'D';
    l_pk     := TO_CHAR(:OLD.customer_id);
    l_old    := :OLD.customer_ref || '|' || :OLD.last_name || '|' || :OLD.status;
  END IF;

  pkg_audit.write_audit(p_table_name => 'CUSTOMER',
                        p_pk_value   => l_pk,
                        p_action     => l_action,
                        p_old_row    => l_old,
                        p_new_row    => l_new);
END trg_aiud_customer;
/

