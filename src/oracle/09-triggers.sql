-- =====================================================================================
-- 19-21 : COMPOUND TRIGGERS -- the hardest shape in the schema
-- =====================================================================================
-- MIGRATION NOTE (H-26): a compound trigger is one object with up to four timing
-- sections that share state for the duration of a single statement. It exists to dodge
-- Oracle's mutating-table error: buffer the rows as they fly past in AFTER EACH ROW, then
-- act on them in AFTER STATEMENT when the table is no longer mutating.
--
-- PostgreSQL has NO mutating-table restriction, so the entire reason for the pattern is
-- gone. The right conversion is a single FOR EACH STATEMENT trigger over a transition
-- table (REFERENCING NEW TABLE AS new_rows), which is simpler and faster than the
-- original. A *mechanical* conversion into three separate PostgreSQL triggers is broken:
-- the shared collection has nowhere to live between them, so the AFTER STATEMENT section
-- sees an empty buffer and silently does nothing. That failure produces no error, no
-- warning, and correct-looking output -- it just stops maintaining the data.
-- -------------------------------------------------------------------------------------

CREATE OR REPLACE TRIGGER trg_cmp_inventory_stock
  FOR INSERT OR UPDATE ON inventory_stock
  COMPOUND TRIGGER

  TYPE t_num IS TABLE OF NUMBER        INDEX BY PLS_INTEGER;
  TYPE t_vc  IS TABLE OF VARCHAR2(200) INDEX BY PLS_INTEGER;

  g_keys  t_vc;
  g_short t_num;
  g_n     PLS_INTEGER := 0;

  BEFORE STATEMENT IS
  BEGIN
    g_keys.DELETE;
    g_short.DELETE;
    g_n := 0;
  END BEFORE STATEMENT;

  AFTER EACH ROW IS
  BEGIN
    -- qty_available is a virtual column (H-17): readable through :NEW, never writable.
    IF :NEW.qty_available < 0 THEN
      g_n := g_n + 1;
      g_keys(g_n)  := TO_CHAR(:NEW.location_id) || '/' || TO_CHAR(:NEW.variant_id);
      g_short(g_n) := :NEW.qty_available;
    END IF;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
  BEGIN
    -- MIGRATION NOTE: Oracle forbids RETURN anywhere inside a COMPOUND TRIGGER body
    -- (PLS-00678), so the usual "guard clause and bail out early" shape is not available
    -- here -- the test has to be inverted into a positive IF around the whole body. A
    -- PostgreSQL statement trigger is an ordinary function, so the converter is free to
    -- put the early RETURN back; watch that it does not also swallow the empty-buffer case.
    IF g_n > 0 THEN
      -- MIGRATION NOTE (H-10): FORALL inside a trigger. On PostgreSQL this collapses to a
      -- single INSERT ... SELECT over the transition table -- shorter, faster and clearer.
      FORALL i IN 1 .. g_n
        INSERT INTO data_quality_issue (issue_id, rule_code, entity_name, entity_key,
                                        severity, detail)
        VALUES (pkg_utils.next_id('SEQ_DQ_ISSUE_ID'), 'NEGATIVE_AVAILABLE',
                'INVENTORY_STOCK', g_keys(i), 'ERROR',
                'qty_available went negative: ' || TO_CHAR(g_short(i)));

      DBMS_OUTPUT.PUT_LINE('trg_cmp_inventory_stock: ' || g_n
                           || ' negative-availability rows recorded');
    END IF;
  END AFTER STATEMENT;

END trg_cmp_inventory_stock;
/

CREATE OR REPLACE TRIGGER trg_cmp_sales_order_line
  FOR INSERT OR UPDATE OR DELETE ON sales_order_line
  COMPOUND TRIGGER

  TYPE t_num IS TABLE OF NUMBER INDEX BY PLS_INTEGER;

  g_variant t_num;
  g_loc     t_num;
  g_qty     t_num;
  g_n       PLS_INTEGER := 0;

  BEFORE STATEMENT IS
  BEGIN
    g_variant.DELETE;
    g_loc.DELETE;
    g_qty.DELETE;
    g_n := 0;
  END BEFORE STATEMENT;

  AFTER EACH ROW IS
    l_delta NUMBER;
  BEGIN
    -- Reserve on insert, release on delete, adjust on update. The delta arithmetic is
    -- the reason the rows must be buffered rather than applied one at a time: several
    -- lines of the same order may hit the same stock row in one statement.
    IF INSERTING THEN
      l_delta := :NEW.qty;
    ELSIF DELETING THEN
      l_delta := -:OLD.qty;
    ELSE
      l_delta := NVL(:NEW.qty, 0) - NVL(:OLD.qty, 0);
    END IF;

    IF l_delta <> 0 THEN
      g_n := g_n + 1;
      g_variant(g_n) := CASE WHEN DELETING THEN :OLD.variant_id ELSE :NEW.variant_id END;
      g_loc(g_n)     := CASE WHEN DELETING THEN :OLD.fulfil_location_id
                             ELSE :NEW.fulfil_location_id END;
      g_qty(g_n)     := l_delta;
    END IF;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
  BEGIN
    -- MIGRATION NOTE: same PLS-00678 restriction as trg_cmp_inventory_stock -- no RETURN
    -- inside a compound trigger, so the guard is inverted rather than an early exit.
    IF g_n > 0 THEN
      FORALL i IN 1 .. g_n
        UPDATE inventory_stock
           SET qty_reserved     = GREATEST(NVL(qty_reserved, 0) + g_qty(i), 0)
             , last_movement_ts = SYSTIMESTAMP
         WHERE location_id = g_loc(i)
           AND variant_id  = g_variant(i);

      DBMS_OUTPUT.PUT_LINE('trg_cmp_sales_order_line: ' || g_n
                           || ' reservation deltas applied');
    END IF;
  END AFTER STATEMENT;

END trg_cmp_sales_order_line;
/

CREATE OR REPLACE TRIGGER trg_cmp_loyalty_txn
  FOR INSERT OR UPDATE ON loyalty_transaction
  COMPOUND TRIGGER

  TYPE t_num IS TABLE OF NUMBER INDEX BY PLS_INTEGER;

  g_loyalty t_num;
  g_n       PLS_INTEGER := 0;

  BEFORE STATEMENT IS
  BEGIN
    g_loyalty.DELETE;
    g_n := 0;
  END BEFORE STATEMENT;

  AFTER EACH ROW IS
  BEGIN
    g_n := g_n + 1;
    g_loyalty(g_n) := :NEW.loyalty_id;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
    l_sum     NUMBER;
    l_balance NUMBER;
  BEGIN
    -- This SELECT is the whole reason the trigger is compound: reading
    -- loyalty_transaction from an AFTER EACH ROW section would raise ORA-04091, because
    -- the table is mid-statement. In the AFTER STATEMENT section it is legal.
    --
    -- On PostgreSQL there is no such restriction, so a converter has no signal that this
    -- structure was ever necessary -- and if it flattens the trigger into a row-level
    -- one, the code will work, which is the worst outcome: the pattern gets copied.
    FOR i IN 1 .. g_n LOOP
      SELECT NVL(SUM(points_delta), 0)
        INTO l_sum
        FROM loyalty_transaction
       WHERE loyalty_id = g_loyalty(i);

      SELECT points_balance
        INTO l_balance
        FROM loyalty_account
       WHERE loyalty_id = g_loyalty(i);

      IF l_sum <> l_balance THEN
        INSERT INTO data_quality_issue (issue_id, rule_code, entity_name, entity_key,
                                        severity, detail)
        VALUES (pkg_utils.next_id('SEQ_DQ_ISSUE_ID'), 'LOYALTY_LEDGER_DRIFT',
                'LOYALTY_ACCOUNT', TO_CHAR(g_loyalty(i)), 'WARN',
                'ledger sum ' || l_sum || ' <> account balance ' || l_balance);
      END IF;
    END LOOP;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      NULL;
  END AFTER STATEMENT;

END trg_cmp_loyalty_txn;
