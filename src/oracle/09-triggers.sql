CREATE OR REPLACE TRIGGER trg_bu_product
  BEFORE UPDATE ON product
  FOR EACH ROW
BEGIN
  -- margin_pct is virtual (H-17) and is never assigned.
  IF :OLD.status = 'DISCONTINUED' AND :NEW.status = 'ACTIVE' THEN
    RAISE_APPLICATION_ERROR(-20603,
      'SKU ' || :OLD.sku || ' is discontinued and cannot be reactivated directly');
  END IF;

  IF :NEW.list_price < :NEW.unit_cost THEN
    -- Sold below cost: legal, but somebody should know.
    INSERT INTO data_quality_issue (issue_id, rule_code, entity_name, entity_key,
                                    severity, detail)
    VALUES (pkg_utils.next_id('SEQ_DQ_ISSUE_ID'), 'NEGATIVE_MARGIN', 'PRODUCT',
            :NEW.sku, 'WARN',
            'list_price ' || :NEW.list_price || ' below unit_cost ' || :NEW.unit_cost);
  END IF;
END trg_bu_product;
/

CREATE OR REPLACE TRIGGER trg_bu_store_area
  BEFORE UPDATE OF selling_area_sqm, closed_date ON store
  FOR EACH ROW
  WHEN (NEW.selling_area_sqm <> OLD.selling_area_sqm OR NEW.closed_date IS NOT NULL)
BEGIN
  -- MIGRATION NOTE (H-25 + H-38): the WHEN condition compares two possibly-NULL numbers
  -- with <>, so it is UNKNOWN -- and therefore false -- whenever either side is NULL.
  -- That is identical in PostgreSQL, which is worth stating because it looks like a bug
  -- and is not. What is NOT identical: store.legacy_migration_notes is a LONG column, and
  -- Oracle forbids referencing it through :NEW or :OLD at all (H-33). After conversion to
  -- text that restriction disappears, so a converted trigger could reference it -- and a
  -- helpful converter that "restores" the missing column reference changes behaviour.
  IF :NEW.closed_date IS NOT NULL AND :OLD.closed_date IS NULL THEN
    pkg_audit.write_audit('STORE', TO_CHAR(:OLD.store_id), 'U',
                          'closed_date=NULL',
                          'closed_date=' || TO_CHAR(:NEW.closed_date, 'YYYY-MM-DD'));
  END IF;
END trg_bu_store_area;
