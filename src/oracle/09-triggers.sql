CREATE OR REPLACE TRIGGER trg_io_open_purchase_orders
  INSTEAD OF INSERT OR UPDATE OR DELETE ON v_open_purchase_orders
  FOR EACH ROW
DECLARE
  l_po_id NUMBER;
BEGIN
  IF INSERTING THEN
    l_po_id := NVL(:NEW.po_id, pkg_utils.next_id('SEQ_PO_ID'));

    INSERT INTO purchase_order (po_id, po_number, supplier_id, warehouse_id,
                                order_date, expected_date, status, currency_code,
                                order_total, approved_by_employee_id)
    VALUES (l_po_id,
            NVL(:NEW.po_number, 'PO' || LPAD(TO_CHAR(l_po_id), 12, '0')),
            :NEW.supplier_id,
            :NEW.warehouse_id,
            NVL(:NEW.order_date, TRUNC(SYSDATE)),
            NVL(:NEW.expected_date, TRUNC(SYSDATE) + 14),
            NVL(:NEW.status, 'DRAFT'),
            :NEW.currency_code,
            NVL(:NEW.order_total, 0),
            :NEW.approved_by_employee_id);

  ELSIF UPDATING THEN
    -- Routed through the package rather than issued inline, so the state machine and its
    -- user-defined exceptions (H-28) stay in one place. An INSTEAD OF trigger calling
    -- business logic is common and converts fine; the exceptions it can raise are the
    -- part that needs the SQLCODE-to-SQLSTATE mapping.
    IF :NEW.status = 'SENT' AND :OLD.status <> 'SENT' THEN
      pkg_purchasing.send_po(:OLD.po_id);
    ELSIF :NEW.status = 'CANCELLED' AND :OLD.status <> 'CANCELLED' THEN
      pkg_purchasing.cancel_po(:OLD.po_id, 'VIEW_UPDATE');
    ELSE
      UPDATE purchase_order
         SET expected_date           = :NEW.expected_date
           , approved_by_employee_id = :NEW.approved_by_employee_id
       WHERE po_id = :OLD.po_id;
    END IF;

  ELSE
    pkg_purchasing.cancel_po(:OLD.po_id, 'VIEW_DELETE');
  END IF;
END trg_io_open_purchase_orders;
