-- =====================================================================================
-- 7 : trg_bi_sales_order_web -- BEFORE INSERT with a WHEN clause
-- =====================================================================================
-- MIGRATION NOTE (H-25): the WHEN clause. PostgreSQL has WHEN too and the syntax is
-- nearly identical -- but note the colons: Oracle writes WHEN (NEW.channel_code = 'WEB')
-- with a bare NEW in the condition and :NEW inside the body, while PostgreSQL uses NEW in
-- both. A converter that blindly strips or adds colons breaks one or the other.
-- PostgreSQL also forbids WHEN on INSTEAD OF triggers, and forbids referencing OLD in a
-- WHEN clause on INSERT -- restrictions Oracle does not have.
-- -------------------------------------------------------------------------------------
CREATE OR REPLACE TRIGGER trg_bi_sales_order_web
  BEFORE INSERT ON sales_order
  FOR EACH ROW
  WHEN (NEW.channel_code = 'WEB')
BEGIN
  IF :NEW.source_ip IS NULL THEN
    :NEW.source_ip := SUBSTR(SYS_CONTEXT('USERENV', 'IP_ADDRESS'), 1, 45);
  END IF;

  IF :NEW.shipping_amount IS NULL THEN
    :NEW.shipping_amount := 0;
  END IF;

  -- Web orders never come from a named salesperson.
  :NEW.sales_employee_id := NULL;
END trg_bi_sales_order_web;
/


