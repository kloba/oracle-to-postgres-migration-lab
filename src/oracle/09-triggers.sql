CREATE OR REPLACE TRIGGER trg_au_order_payment
  AFTER UPDATE ON order_payment
  FOR EACH ROW
  WHEN (NEW.status <> OLD.status)
BEGIN
  -- MIGRATION NOTE (T-05 / H-31): NVL, not DECODE. DECODE is a SQL function and Oracle
  -- rejects it in a PL/SQL expression with PLS-00204 -- it is only legal inside a SQL
  -- statement. That restriction is easy to forget when converting, because orafce
  -- provides decode() as an ordinary PostgreSQL function callable from PL/pgSQL, so the
  -- converted code can end up *more* permissive than the original. NVL converts to
  -- COALESCE, with the usual caveat that NVL evaluates both arguments and COALESCE
  -- short-circuits.
  pkg_audit.write_audit('ORDER_PAYMENT',
                        TO_CHAR(:OLD.payment_id),
                        'U',
                        NVL(:OLD.status, 'UNKNOWN'),
                        NVL(:NEW.status, 'UNKNOWN'));

  IF :NEW.status = 'CAPTURED' AND :OLD.status <> 'CAPTURED' THEN
    UPDATE sales_order
       SET status = 'PLACED'
     WHERE order_id = :NEW.order_id
       AND status   = 'CART';
  END IF;
END trg_au_order_payment;
