CREATE OR REPLACE TRIGGER trg_ad_coupon_audit
  AFTER DELETE ON coupon
  FOR EACH ROW
DECLARE
  -- MIGRATION NOTE (H-01): a typed NULL, not a bare one. pkg_audit.write_audit is
  -- overloaded on VARCHAR2 and CLOB and an untyped NULL is a candidate for both, which
  -- Oracle rejects as PLS-00307 -- the same ambiguity PostgreSQL will raise as
  -- "function is not unique" at far more call sites after conversion.
  l_new_row VARCHAR2(1) := NULL;
BEGIN
  -- MIGRATION NOTE (H-02): the autonomous audit call from a DELETE trigger is the clearest
  -- statement of the problem. A deleted coupon must leave a trace even if the enclosing
  -- transaction rolls back -- that is the whole reason pkg_audit is autonomous. Convert it
  -- to an in-transaction INSERT and the trace vanishes with the rollback; convert it to a
  -- dblink call and you open a connection per deleted coupon. Neither is free, and the
  -- decision belongs to the business, not the converter.
  pkg_audit.write_audit('COUPON',
                        TO_CHAR(:OLD.coupon_id),
                        'D',
                        :OLD.coupon_code || '|promo=' || TO_CHAR(:OLD.promotion_id)
                          || '|redemptions=' || TO_CHAR(:OLD.redemption_count),
                        l_new_row);
END trg_ad_coupon_audit;
