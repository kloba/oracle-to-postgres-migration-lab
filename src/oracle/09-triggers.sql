-- =====================================================================================
-- 1-6 : BEFORE INSERT ... FOR EACH ROW -- surrogate key assignment
-- =====================================================================================
-- MIGRATION NOTE (H-22 + H-25): the "assign the key if the caller did not" pattern. On
-- PostgreSQL the idiomatic replacement is GENERATED BY DEFAULT AS IDENTITY, which removes
-- the trigger entirely -- but it also changes INSERT behaviour for explicit values and
-- for the sequence's own currval, so the lab keeps explicit sequences to avoid muddying
-- the comparison (docs/design.md H-22). If you do convert to IDENTITY, remember Oracle's
-- CACHE is instance-wide and PostgreSQL's is per session, so values scatter far more
-- visibly across concurrent connections.
-- -------------------------------------------------------------------------------------

CREATE OR REPLACE TRIGGER trg_bi_address
  BEFORE INSERT ON address
  FOR EACH ROW
BEGIN
  IF :NEW.address_id IS NULL THEN
    :NEW.address_id := pkg_utils.next_id('SEQ_ADDRESS_ID');
  END IF;
  -- normalised_key is a virtual column (H-17) and cannot be assigned here. On PostgreSQL
  -- it becomes GENERATED ALWAYS ... STORED, which also cannot be assigned -- one of the
  -- few places the two dialects agree on a restriction.
  :NEW.line1 := TRIM(:NEW.line1);
  :NEW.city  := TRIM(:NEW.city);
END trg_bi_address;
/

CREATE OR REPLACE TRIGGER trg_bi_customer
  BEFORE INSERT ON customer
  FOR EACH ROW
BEGIN
  IF :NEW.customer_id IS NULL THEN
    :NEW.customer_id := pkg_utils.next_id('SEQ_CUSTOMER_ID');
  END IF;

  IF :NEW.customer_ref IS NULL THEN
    :NEW.customer_ref := 'CU' || LPAD(TO_CHAR(:NEW.customer_id), 12, '0');
  END IF;

  -- MIGRATION NOTE (H-38): TRIM of a single-space email yields '' which Oracle stores as
  -- NULL, so the row satisfies "email IS NULL" downstream. PostgreSQL stores an empty
  -- string, the row fails that test, and the unique index on LOWER(email) starts
  -- rejecting a second blank where Oracle allowed unlimited NULLs. Nothing errors at
  -- conversion time. The first symptom is a duplicate-key error in production.
  :NEW.email := LOWER(TRIM(:NEW.email));

  IF :NEW.created_ts IS NULL THEN
    :NEW.created_ts := SYSTIMESTAMP;
  END IF;
END trg_bi_customer;
/

CREATE OR REPLACE TRIGGER trg_bi_employee
  BEFORE INSERT ON employee
  FOR EACH ROW
BEGIN
  IF :NEW.employee_id IS NULL THEN
    :NEW.employee_id := pkg_utils.next_id('SEQ_EMPLOYEE_ID');
  END IF;

  IF :NEW.employee_number IS NULL THEN
    :NEW.employee_number := 'E' || LPAD(TO_CHAR(:NEW.employee_id), 8, '0');
  END IF;

  -- full_name and is_active are virtual columns and are not assignable (H-17).
  :NEW.first_name := INITCAP(TRIM(:NEW.first_name));
  :NEW.last_name  := INITCAP(TRIM(:NEW.last_name));
END trg_bi_employee;
/

CREATE OR REPLACE TRIGGER trg_bi_supplier
  BEFORE INSERT ON supplier
  FOR EACH ROW
DECLARE
  l_contact t_contact;
BEGIN
  IF :NEW.supplier_id IS NULL THEN
    :NEW.supplier_id := pkg_utils.next_id('SEQ_SUPPLIER_ID');
  END IF;

  IF :NEW.onboarded_ts IS NULL THEN
    :NEW.onboarded_ts := SYSTIMESTAMP;
  END IF;

  -- MIGRATION NOTE (H-03): primary_contact is an object column and this calls one of its
  -- member functions. PostgreSQL sees a composite with no methods, so the converted
  -- trigger function must call a standalone is_valid_email(NEW.primary_contact). If the
  -- type converted but the methods did not, this trigger is where it surfaces -- a long
  -- way from the type definition that actually caused the failure.
  l_contact := :NEW.primary_contact;
  IF l_contact IS NOT NULL AND l_contact.is_valid_email() <> 'Y' THEN
    :NEW.is_approved := 'N';
  END IF;
END trg_bi_supplier;
/

CREATE OR REPLACE TRIGGER trg_bi_promotion
  BEFORE INSERT ON promotion
  FOR EACH ROW
BEGIN
  IF :NEW.promotion_id IS NULL THEN
    :NEW.promotion_id := pkg_utils.next_id('SEQ_PROMOTION_ID');
  END IF;

  IF :NEW.spent_amount IS NULL THEN
    :NEW.spent_amount := 0;
  END IF;

  -- MIGRATION NOTE (H-37): start_ts and end_ts are TSLTZ. This comparison runs in the
  -- session time zone, so the same INSERT can pass in London and fail in Tokyo. It is a
  -- pre-existing Oracle bug, faithfully preserved, and converting it to timestamptz
  -- preserves it again -- which is the honest outcome. Fixing it is a separate change.
  IF :NEW.end_ts <= :NEW.start_ts THEN
    RAISE_APPLICATION_ERROR(-20601, 'Promotion end_ts must be after start_ts');
  END IF;
END trg_bi_promotion;
/

CREATE OR REPLACE TRIGGER trg_bi_return_request
  BEFORE INSERT ON return_request
  FOR EACH ROW
BEGIN
  IF :NEW.return_id IS NULL THEN
    :NEW.return_id := pkg_utils.next_id('SEQ_RETURN_ID');
  END IF;

  -- MIGRATION NOTE (H-22): seq_rma_cycle is CYCLE MAXVALUE 999999 NOCACHE, so RMA
  -- numbers wrap. PostgreSQL supports CYCLE and MAXVALUE with the same spelling, so the
  -- DDL converts -- but a cycling sequence with no unique constraint behind it is a
  -- collision waiting to happen on either engine, and the NOCACHE that made Oracle's
  -- numbering near-gapless costs throughput in PostgreSQL for the same reason.
  IF :NEW.rma_number IS NULL THEN
    :NEW.rma_number := 'RMA' || TO_CHAR(SYSDATE, 'YY')
                       || LPAD(TO_CHAR(seq_rma_cycle.NEXTVAL), 6, '0');
  END IF;

  IF :NEW.requested_ts IS NULL THEN
    :NEW.requested_ts := SYSTIMESTAMP;
  END IF;
END trg_bi_return_request;
