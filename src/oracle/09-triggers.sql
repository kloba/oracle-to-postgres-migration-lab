-- =====================================================================================
-- 22-24 : INSTEAD OF triggers on the updatable views
-- =====================================================================================
-- MIGRATION NOTE (H-27): the trigger case that converts cleanly. PostgreSQL has INSTEAD
-- OF triggers on views with the same name and nearly the same semantics. Two differences
-- to watch. First, the function must RETURN NEW (or OLD on DELETE) or the statement
-- reports zero rows affected and the caller concludes it failed. Second, PostgreSQL
-- forbids a WHEN clause on an INSTEAD OF trigger and requires it to be FOR EACH ROW --
-- both restrictions Oracle does not impose.
-- -------------------------------------------------------------------------------------

CREATE OR REPLACE TRIGGER trg_io_customer_360
  INSTEAD OF INSERT OR UPDATE OR DELETE ON v_customer_360
  FOR EACH ROW
BEGIN
  IF INSERTING THEN
    INSERT INTO customer (customer_id, customer_ref, first_name, last_name, email,
                          mobile_phone, birth_date, home_country_code,
                          preferred_store_id, primary_address_id, marketing_optin,
                          status, created_ts)
    VALUES (:NEW.customer_id,
            NVL(:NEW.customer_ref, 'CU-PENDING'),
            :NEW.first_name,
            :NEW.last_name,
            LOWER(TRIM(:NEW.email)),
            :NEW.mobile_phone,
            :NEW.birth_date,
            :NEW.home_country_code,
            :NEW.preferred_store_id,
            :NEW.primary_address_id,
            NVL(:NEW.marketing_optin, 'N'),
            NVL(:NEW.customer_status, 'ACTIVE'),
            SYSTIMESTAMP);

    IF :NEW.card_number IS NOT NULL AND :NEW.customer_id IS NOT NULL THEN
      INSERT INTO loyalty_account (loyalty_id, customer_id, card_number, tier_code,
                                   points_balance, lifetime_points, enrolled_date,
                                   status)
      VALUES (pkg_utils.next_id('SEQ_LOYALTY_ID'),
              :NEW.customer_id,
              :NEW.card_number,
              NVL(:NEW.tier_code, 'BRONZE'),
              NVL(:NEW.points_balance, 0),
              NVL(:NEW.lifetime_points, 0),
              TRUNC(SYSDATE),
              'ACTIVE');
    END IF;

  ELSIF UPDATING THEN
    UPDATE customer
       SET first_name         = :NEW.first_name
         , last_name          = :NEW.last_name
         , email              = LOWER(TRIM(:NEW.email))
         , mobile_phone       = :NEW.mobile_phone
         , marketing_optin    = :NEW.marketing_optin
         , preferred_store_id = :NEW.preferred_store_id
         , primary_address_id = :NEW.primary_address_id
         , status             = :NEW.customer_status
     WHERE customer_id = :OLD.customer_id;

    -- The view spans six tables; only two of them are writable through it. Any attempt
    -- to change country_name or tier_name is silently ignored -- deliberately, because
    -- that is what the call-centre screen expects, and worth knowing before somebody
    -- converts it and wonders why those columns look read-only.
    IF :NEW.points_balance IS NOT NULL AND :OLD.loyalty_id IS NOT NULL THEN
      UPDATE loyalty_account
         SET points_balance = :NEW.points_balance
           , tier_code      = NVL(:NEW.tier_code, tier_code)
       WHERE loyalty_id = :OLD.loyalty_id;
    END IF;

  ELSE
    -- GDPR soft delete: the row stays, the identity goes. 'ERASED' is one of the four
    -- values ck_customer_status permits -- worth noting because a converter that renames
    -- or drops a CHECK constraint turns this INSTEAD OF trigger from a guarded operation
    -- into an unguarded one, and nothing about the trigger text changes.
    UPDATE customer
       SET status          = 'ERASED'
         , email           = NULL
         , mobile_phone    = NULL
         , gdpr_erasure_ts = SYSTIMESTAMP
     WHERE customer_id = :OLD.customer_id;
  END IF;
END trg_io_customer_360;
