--
-- MIGRATION NOTE (structural, applies to every trigger in this file): an Oracle trigger
-- is ONE object containing both the firing condition and the body. A PostgreSQL trigger
-- is TWO: a CREATE FUNCTION ... RETURNS TRIGGER holding the body, and a CREATE TRIGGER
-- binding it to the table. So the converted schema has roughly twice as many objects in
-- this category, the function names have to be invented (and made unique across the
-- whole schema, not just per table), and the association between a trigger and its logic
-- becomes a name convention rather than a language construct.
--
-- MIGRATION NOTE (H-25, the single most common conversion bug): a PostgreSQL BEFORE ROW
-- trigger function MUST end with RETURN NEW. If it falls off the end returning NULL, the
-- row is silently discarded -- the INSERT reports success and nothing is stored. Every
-- trg_bi_* trigger below is exposed to this. Check the generated function bodies, not
-- the trigger declarations.
-- =====================================================================================

