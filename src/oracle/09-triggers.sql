CREATE OR REPLACE TRIGGER trg_bu_app_parameter
  BEFORE UPDATE ON app_parameter
  FOR EACH ROW
BEGIN
  :NEW.updated_ts := SYSTIMESTAMP;
  -- MIGRATION NOTE (H-39): SYS_CONTEXT('USERENV','SESSION_USER') becomes session_user on
  -- PostgreSQL, which is close. The custom-namespace reads elsewhere in this schema are
  -- the problem, not this one -- see trg_aiud_customer.
  :NEW.updated_by := SUBSTR(SYS_CONTEXT('USERENV', 'SESSION_USER'), 1, 30);

  IF :OLD.is_encrypted = 'Y' AND :NEW.is_encrypted = 'N' THEN
    RAISE_APPLICATION_ERROR(-20602,
      'Parameter ' || :OLD.param_name || ' cannot be un-encrypted in place');
  END IF;
END trg_bu_app_parameter;
