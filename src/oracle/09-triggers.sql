-- =====================================================================================
-- 14-15 : the FOLLOWS pair on gl_journal_line
-- =====================================================================================
-- MIGRATION NOTE (H-25): FOLLOWS guarantees firing order between two triggers on the
-- same table at the same timing point. PostgreSQL has no FOLLOWS -- it fires triggers in
-- alphabetical *name* order. These two are named _a and _b, so they happen to convert
-- correctly by luck, and that luck is worth pointing out loudly: rename either one and
-- the order silently reverses. If order matters after conversion, encode it in the name
-- deliberately (10_, 20_ prefixes) or merge the two bodies into one trigger.
-- -------------------------------------------------------------------------------------

CREATE OR REPLACE TRIGGER trg_ar_gl_journal_line_a
  AFTER INSERT ON gl_journal_line
  FOR EACH ROW
BEGIN
  IF :NEW.debit_amount > 0 AND :NEW.credit_amount > 0 THEN
    RAISE_APPLICATION_ERROR(-20604,
      'Journal line ' || :NEW.journal_id || '/' || :NEW.line_no
      || ' may not carry both a debit and a credit');
  END IF;

  IF :NEW.fx_rate IS NULL AND :NEW.currency_code <> 'GBP' THEN
    RAISE_APPLICATION_ERROR(-20605,
      'Journal line in ' || :NEW.currency_code || ' requires an fx_rate');
  END IF;
END trg_ar_gl_journal_line_a;
/

CREATE OR REPLACE TRIGGER trg_ar_gl_journal_line_b
  AFTER INSERT ON gl_journal_line
  FOR EACH ROW
  FOLLOWS trg_ar_gl_journal_line_a
BEGIN
  -- Runs only once _a has passed its validations. On PostgreSQL that ordering is a
  -- naming coincidence.
  UPDATE gl_journal
     SET description = SUBSTR(NVL(description, 'Journal ' || :NEW.journal_id), 1, 300)
   WHERE journal_id = :NEW.journal_id
     AND status     = 'DRAFT';
END trg_ar_gl_journal_line_b;
/


-- =====================================================================================
-- 16-18 : statement-level triggers
-- =====================================================================================
-- MIGRATION NOTE (H-25): a statement-level trigger cannot see NEW or OLD in either
-- dialect -- but PostgreSQL offers something Oracle does not: transition tables, declared
-- with REFERENCING NEW TABLE AS new_rows. That is the idiomatic way to convert both these
-- statement triggers *and* the three compound triggers below, and it is usually a better
-- design than the original. The conversion is therefore an upgrade opportunity that a
-- mechanical translation will miss entirely.
-- -------------------------------------------------------------------------------------

CREATE OR REPLACE TRIGGER trg_bius_gl_period
  BEFORE INSERT OR UPDATE ON gl_period
DECLARE
  l_open NUMBER;
BEGIN
  -- Statement level, so gl_period is not mutating and can be queried freely. In a ROW
  -- trigger this same SELECT would raise ORA-04091. PostgreSQL has no mutating-table
  -- restriction at all, which means the *reason* this trigger is statement-level
  -- disappears on the target -- and so does the safety it was providing.
  SELECT COUNT(*) INTO l_open FROM gl_period WHERE status = 'OPEN';

  IF l_open > 2 THEN
    RAISE_APPLICATION_ERROR(-20606,
      'Too many OPEN GL periods (' || l_open || '); close one before opening another');
  END IF;

  DBMS_OUTPUT.PUT_LINE('trg_bius_gl_period: ' || l_open || ' period(s) currently OPEN');
END trg_bius_gl_period;
/

CREATE OR REPLACE TRIGGER trg_as_price_list_item_reprice
  AFTER DELETE ON price_list_item
DECLARE
  l_orphans NUMBER;
BEGIN
  -- A price row was removed. Anything still selling at that price is now unpriced, and
  -- the pricing cache in pkg_pricing is stale for the whole session (H-43).
  pkg_pricing.reset_cache;

  SELECT COUNT(*)
    INTO l_orphans
    FROM product_variant pv
   WHERE pv.is_active = 'Y'
     AND NOT EXISTS (SELECT 1 FROM price_list_item pli
                      WHERE pli.variant_id = pv.variant_id);

  IF l_orphans > 0 THEN
    INSERT INTO data_quality_issue (issue_id, rule_code, entity_name, entity_key,
                                    severity, detail)
    VALUES (pkg_utils.next_id('SEQ_DQ_ISSUE_ID'), 'UNPRICED_VARIANT',
            'PRODUCT_VARIANT', 'ALL', 'WARN',
            l_orphans || ' active variants have no price list entry after a delete');
  END IF;
END trg_as_price_list_item_reprice;
/

CREATE OR REPLACE TRIGGER trg_as_sales_order_line_stmt
  AFTER INSERT ON sales_order_line
BEGIN
  -- Nothing about the inserted rows is visible here -- no NEW, no OLD, no count. That is
