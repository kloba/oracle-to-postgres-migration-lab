--------------------------------------------------------------------------------
-- The two NOCACHE sequences (H-22).
--
-- pkg_audit and pkg_error are PRAGMA AUTONOMOUS_TRANSACTION (H-02), so their
-- rows survive a rollback of the change they describe. Gap-free-ish numbering
-- matters there: an auditor reading audit_log wants to know that a missing
-- audit_id means something. NOCACHE costs a recursive update to SEQ$ per call
-- and is the deliberate trade.
--
-- NOCACHE is also the only safe conversion target for these two, because
-- PostgreSQL's per-session cache would scatter audit identifiers across
-- connections far more aggressively than Oracle's shared cache does.
--------------------------------------------------------------------------------
CREATE SEQUENCE seq_audit_id
  START WITH 1 INCREMENT BY 1 NOMAXVALUE NOCYCLE NOCACHE;

CREATE SEQUENCE seq_error_id
  START WITH 1 INCREMENT BY 1 NOMAXVALUE NOCYCLE NOCACHE;

--------------------------------------------------------------------------------
-- The CYCLE sequence (H-22).
--
-- RMA numbers are a six-digit field on a printed returns label inherited from
-- the 1990s system, so the counter wraps rather than overflowing the form.
-- return_request.rma_number combines this with a year prefix, and uq_rma_number
-- is what actually guarantees uniqueness once the sequence wraps.
--
-- CYCLE plus MAXVALUE converts one-to-one. NOCACHE is required alongside it
-- here: a cached cycling sequence can lose the values sitting in the cache at
-- the moment it wraps, which on a printed legal document is not acceptable.
--------------------------------------------------------------------------------
CREATE SEQUENCE seq_rma_cycle
  START WITH 1 INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999 CYCLE NOCACHE;

--------------------------------------------------------------------------------
-- Verification.
--
-- 25 sequences: 22 ordinary CACHE 20, 2 NOCACHE, 1 CYCLE + MAXVALUE + NOCACHE.
-- The 15 names the PL/SQL layer compiles against are asserted individually --
-- a missing sequence there does not fail here, it fails much later as an
-- INVALID package body, which is a far worse place to discover it.
--------------------------------------------------------------------------------
DECLARE
  TYPE t_name_list IS TABLE OF VARCHAR2(30);

  -- The eight names below marked (dyn) are reached from 07-packages.sql as
  -- pkg_utils.next_id('SEQ_...'), i.e. a string inside dynamic SQL. Those do NOT
  -- fail as an INVALID package body -- they compile perfectly and raise
  -- ORA-02289 the first time the code path runs, possibly months later. Asserting
  -- them here is the only place the mismatch is cheap to find.
  l_required  t_name_list := t_name_list(
    'SEQ_AUDIT_ID',      'SEQ_ERROR_ID',      'SEQ_RMA_CYCLE',
    'SEQ_ADDRESS_ID',    'SEQ_EMPLOYEE_ID',   'SEQ_CUSTOMER_ID',
    'SEQ_PRODUCT_ID',    'SEQ_ORDER_ID',      'SEQ_PO_ID',
    'SEQ_RETURN_ID',     'SEQ_MOVEMENT_ID',   'SEQ_LOYALTY_TXN_ID',
    'SEQ_JOURNAL_ID',    'SEQ_SHIPMENT_ID',
    'SEQ_DQ_ISSUE_ID',   -- (dyn) pkg_data_quality
    'SEQ_RECEIPT_ID');   -- (dyn) pkg_receiving

  l_total     PLS_INTEGER;
  l_nocache   PLS_INTEGER;
  l_cycle     PLS_INTEGER;
  l_stepped   PLS_INTEGER;
  l_missing   VARCHAR2(4000);
  l_found     PLS_INTEGER;
BEGIN
  SELECT COUNT(*) INTO l_total FROM user_sequences;

  SELECT COUNT(*) INTO l_nocache FROM user_sequences WHERE cache_size = 0;

  SELECT COUNT(*) INTO l_cycle
    FROM user_sequences
   WHERE cycle_flag = 'Y' AND max_value = 999999;

  SELECT COUNT(*) INTO l_stepped
    FROM user_sequences WHERE increment_by <> 1;

  FOR i IN 1 .. l_required.COUNT LOOP
    SELECT COUNT(*) INTO l_found
      FROM user_sequences WHERE sequence_name = l_required(i);

    IF l_found = 0 THEN
      l_missing := l_missing || l_required(i) || ' ';
    END IF;
  END LOOP;

  DBMS_OUTPUT.PUT_LINE('Sequences ..........: ' || l_total   || ' (expected 25)');
  DBMS_OUTPUT.PUT_LINE('NOCACHE ............: ' || l_nocache || ' (expected 3)');
  DBMS_OUTPUT.PUT_LINE('CYCLE with MAXVALUE : ' || l_cycle   || ' (expected 1)');
  DBMS_OUTPUT.PUT_LINE('Non-unit INCREMENT .: ' || l_stepped || ' (expected 1)');

  IF l_missing IS NOT NULL THEN
    RAISE_APPLICATION_ERROR(-20050,
      'Sequences required by the PL/SQL layer are missing: ' || l_missing);
  END IF;

  IF l_total <> 25 THEN
    RAISE_APPLICATION_ERROR(-20051,
      'Sequence budget drift: expected 25, got ' || l_total || '.');
  END IF;

  IF l_nocache <> 3 THEN
    RAISE_APPLICATION_ERROR(-20052,
      'H-22 needs exactly 3 NOCACHE sequences (audit, error, rma), got '
      || l_nocache || '.');
  END IF;

  IF l_cycle <> 1 THEN
    RAISE_APPLICATION_ERROR(-20053,
      'H-22 needs exactly 1 CYCLE sequence with MAXVALUE 999999, got '
      || l_cycle || '.');
  END IF;

  IF l_stepped <> 1 THEN
    RAISE_APPLICATION_ERROR(-20054,
      'Expected exactly 1 sequence with a non-unit INCREMENT BY, got '
      || l_stepped || '.');
  END IF;
END;
