-- The non-unit increment. pkg_finance_gl reserves a block of ten identifiers per
-- posting run with a single NEXTVAL and hands them out locally, so a journal and
-- its control totals stay numerically adjacent. Shared with gl_period.period_id.
--
-- INCREMENT BY 10 converts literally to PostgreSQL, but the interaction with
