--------------------------------------------------------------------------------
-- Contoso Store -- Oracle to Azure Database for PostgreSQL migration lab
-- 05-sequences.sql
--
-- 25 sequences. Runs as CONTOSO, after 04-indexes.sql, before the PL/SQL layer.
--
-- Load-order note: this file runs AFTER 02-tables.sql, so no column in the
-- schema carries a sequence in its DEFAULT clause. Keys are assigned by the
-- trg_bi_* triggers and by explicit .NEXTVAL in the packages. That is also the
-- honest choice for the lab: an Oracle sequence used in a DEFAULT converts most
-- naturally to GENERATED BY DEFAULT AS IDENTITY on PostgreSQL, which changes
-- INSERT behaviour for explicit values and would muddy the comparison (H-22).
--
-- Numbering convention: entity sequences START WITH 1000. Identifiers below
-- 1000 are reserved for hand-written reference rows in seed/, so seeding can mix
-- fixed well-known keys with generated ones without collision.
--
-- Hard case H-22 lives here. The syntax maps one-to-one onto PostgreSQL, so this
-- is one of the ten predicted-clean cases -- but the operational behaviour does
-- not map. Oracle's sequence cache is shared across the instance; PostgreSQL's
-- is per session, so CACHE 20 scatters values across concurrent connections far
-- more visibly after conversion. NOCACHE is the safe conversion wherever
-- ordering is assumed, at a throughput cost.
--------------------------------------------------------------------------------

