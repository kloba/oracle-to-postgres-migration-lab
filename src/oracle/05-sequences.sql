-- Re-runnability. Swallow ONLY ORA-02289 "sequence does not exist".
--------------------------------------------------------------------------------
DECLARE
  l_dropped  PLS_INTEGER := 0;

  e_no_such_sequence EXCEPTION;
  PRAGMA EXCEPTION_INIT(e_no_such_sequence, -2289);
BEGIN
  FOR r IN (SELECT sequence_name
              FROM user_sequences
             WHERE sequence_name LIKE 'SEQ\_%' ESCAPE '\')
  LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP SEQUENCE ' || r.sequence_name;
      l_dropped := l_dropped + 1;
    EXCEPTION
      WHEN e_no_such_sequence THEN
        NULL;
    END;
  END LOOP;

  DBMS_OUTPUT.PUT_LINE('Pre-existing sequences dropped: ' || l_dropped);
END;
